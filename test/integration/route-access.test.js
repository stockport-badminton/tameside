// REARCH-04: every route's first middleware declares who may call it (middleware/access.js),
// and the whole table is committed as docs/routes.md. Ported from Stockport
// (league-site __tests__/integration/route-access.test.js).
//
// The table is the review signal. A route that opens, or a `superadmin` that becomes
// `member`, shows as a one-line diff in a file whose only purpose is to be read. That
// signal did not exist for /fixture-gen/publish, which sat behind a bare `secured` while
// rewriting the live season's fixtures, because "no role check" is the absence of a line.
//
// After adding or changing a route:
//   UPDATE_ROUTE_TABLE=1 node --test test/integration/route-access.test.js

const { test } = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const path = require('path');

const { app } = require('../helpers/app');
const { routeTable } = require('../helpers/routeTable');

const TABLE_FILE = path.join(__dirname, '..', '..', 'docs', 'routes.md');
const table = routeTable(app);

function render(rows) {
  const lines = [
    '# Routes',
    '',
    'Generated by `test/integration/route-access.test.js`. Do not edit by hand. After adding',
    'or changing a route: `UPDATE_ROUTE_TABLE=1 node --test test/integration/route-access.test.js`.',
    '',
    'Every route, in registration order (first match wins), with the `access.*` declaration',
    'that is its first middleware. See `middleware/access.js` for what each level means.',
    '`member, then …` enforces the login only; the rest is checked inside the handler.',
    '',
    '| # | Method | Path | Access |',
    '|---:|---|---|---|',
  ];
  for (const r of rows) {
    lines.push(`| ${r.order} | ${r.method} | \`${r.path.replace(/\|/g, '\\|')}\` | ${r.access || '**none**'} |`);
  }
  return lines.join('\n') + '\n';
}

test('finds the whole route table', () => {
  assert.ok(table.length >= 150, `only ${table.length} routes found`);
  const keys = table.map(r => r.method + ' ' + r.path);
  for (const k of ['GET /health', 'GET /tables/:division', 'POST /scorecard-beta', 'POST /fixture-gen/publish']) {
    assert.ok(keys.includes(k), k);
  }
});

test('gives every route exactly one declaration, as its first middleware', () => {
  const bad = table.filter(r => !r.access || r.misplaced || r.declarations > 1)
    .map(r => `${r.method} ${r.path}: ` +
      (!r.access && !r.misplaced ? 'no access.* declaration' :
        r.misplaced ? 'access.* is not the first middleware' : `${r.declarations} declarations`));
  assert.deepStrictEqual(bad, []);
});

// Pinned by name as well as through the table: these rewrite league data or send mail.
test('the season-start and league-structure tools are superadmin', () => {
  const accessOf = (method, p) => (table.find(r => r.method === method && r.path === p) || {}).access;
  for (const p of ['/fixture-gen/publish', '/fixture-gen/regenerate', '/admin/fixture/:id(\\d+)/concede',
                   '/admin/teams/:id(\\d+)/move', '/fixture/reminder', '/scorecard-beta']) {
    assert.strictEqual(accessOf('POST', p), 'superadmin', p);
  }
});

test('matches docs/routes.md', () => {
  const rendered = render(table);
  if (process.env.UPDATE_ROUTE_TABLE) fs.writeFileSync(TABLE_FILE, rendered);
  const committed = fs.existsSync(TABLE_FILE) ? fs.readFileSync(TABLE_FILE, 'utf8') : '';
  // On a mismatch, regenerate (see the top of this file) and read the diff before committing.
  assert.strictEqual(committed, rendered);
});
